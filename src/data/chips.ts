export function chipById(id: string): Chip | undefined {
  for (const cat of CATEGORIES) {
    const found = cat.chips.find((c) => c.id === id);
    if (found) return found;
  }
  return undefined;
}

export function categoryByChipId(id: string): ChipCategory | undefined {
  return CATEGORIES.find((cat) => cat.chips.some((c) => c.id === id));
}

